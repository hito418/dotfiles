##? dot claude - Claude Code rules, skills and agent pack management
##?
##? Usage:
##?    dot claude <command> [<args>...]
##?
##? Commands:
##?    add <names>      Symlink rules, skills and/or agent packs (default: ~/.claude)
##?    remove <names>   Remove rules, skills and/or agent pack symlinks
##?    list             Show available and installed rules/skills/agents
##?    mcp              Set up MCP servers (Context7, GitHub, GitLab)
##?
##? Scope:
##?    Commands target ~/.claude by default. Pass --project to target the
##?    current project's .claude/ (created if missing).
